	"nvim-neo-tree/neo-tree.nvim",
	branch = "v3.x",
	dependencies = {
		"nvim-lua/plenary.nvim",
		"nvim-tree/nvim-web-devicons",
		"MunifTanjim/nui.nvim",
		{
			"s1n7ax/nvim-window-picker",
			version = "2.*",
			config = function()
				require("window-picker").setup({
					filter_rules = {
						include_current_win = false,
						autoselect_one = true,
						bo = {
							filetype = { "neo-tree", "neo-tree-popup", "notify" },
							buftype = { "terminal", "quickfix" },
						},
					},
				})
			end,
		},
	},
	keys = {
		{ "<leader>e", "<cmd>Neotree toggle position=left<cr>", desc = "Toggle Neo-tree" },
		{ "\\", "<cmd>Neotree reveal<cr>", desc = "Reveal current file in Neo-tree" },
	},
	init = function()
		-- Disable netrw before it can initialize
		vim.g.loaded_netrw = 1
		vim.g.loaded_netrwPlugin = 1

		-- FIX: Prevent empty buffer when opening files - use autocmd for lazy-loading
		vim.api.nvim_create_autocmd("BufEnter", {
			group = vim.api.nvim_create_augroup("Neotree_start_directory", { clear = true }),
			desc = "Start Neo-tree with directory",
			once = true,
			callback = function()
				if package.loaded["neo-tree"] then
					return
				else
					local stats = vim.uv.fs_stat(vim.fn.argv(0))
					if stats and stats.type == "directory" then
						require("neo-tree")
					end
				end
			end,
		})
	end,
	config = function()

		require("neo-tree").setup({
			close_if_last_window = false,
			popup_border_style = "rounded",
